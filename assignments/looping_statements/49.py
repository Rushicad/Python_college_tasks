'''Check whether number is strong number'''

while True:
    print("\n1. Hello")
    print("2. Welcome")
    print("3. Exit")

    choice = int(input("Enter your choice: "))

    if choice == 1:
        print("Hello!")
    elif choice == 2:
        print("Welcome!")
    elif choice == 3:
        print("Program Ended")
        break
    else:
        print("Invalid Choice")
